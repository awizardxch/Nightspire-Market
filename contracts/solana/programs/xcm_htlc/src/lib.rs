#[derive(Accounts)]
#[instruction(
    receiver: Pubkey, refund_addr: Pubkey, hashlock: [u8; 32], timelock: i64,
    mint: Option<Pubkey>, amount: u64, fill_id: [u8; 32],
    arbiter: Option<Pubkey>, exclusive_claimer: Option<Pubkey>, exclusive_until: i64
)]
pub struct Initialize<'info> {
    #[account(mut)]
    pub funder: Signer<'info>,
    #[account(
        init,
        payer = funder,
        space = HtlcEscrow::SPACE,
        seeds = [HTLC_SEED, fill_id.as_ref(), hashlock.as_ref()],
        bump,
    )]
    pub escrow: Account<'info, HtlcEscrow>,
    /// CHECK: claim destination. Unvalidated address — a wrong value only harms
    /// the locker who chose it; funds can only ever go here on the claim branch.
    pub receiver: UncheckedAccount<'info>,
    /// CHECK: explicit refund destination. Unvalidated for the same reason.
    pub refund_addr: UncheckedAccount<'info>,
    /// CHECK: SPL only — funder's token account. Validated in the handler when
    /// `mint.is_some()`. Pass any account (e.g. the escrow itself) for SOL fills.
    pub funder_token: UncheckedAccount<'info>,
    /// CHECK: SPL only — pre-created escrow vault token account whose authority
    /// must be the escrow PDA. Validated in the handler when `mint.is_some()`.
    /// Pass any account for SOL fills.
    pub escrow_token: UncheckedAccount<'info>,
    pub system_program: Program<'info, System>,
    /// CHECK: SPL only — must be the SPL Token program. Validated in the handler
    /// when `mint.is_some()`. Pass any account for SOL fills.
    pub token_program: UncheckedAccount<'info>,
}

#[derive(Accounts)]
pub struct Withdraw<'info> {
    /// Anyone may submit (payout is hardcoded to `receiver`); exclusivity is
    /// enforced in the handler.
    pub claimer: Signer<'info>,
    #[account(
        mut,
        seeds = [HTLC_SEED, escrow.fill_id.as_ref(), escrow.hashlock.as_ref()],
        bump = escrow.bump,
        close = receiver,
    )]
    pub escrow: Account<'info, HtlcEscrow>,
    /// CHECK: must equal `escrow.receiver` (checked in handler); receives the
    /// funds and the reclaimed rent.
    #[account(mut)]
    pub receiver: UncheckedAccount<'info>,
    /// CHECK: SPL only — escrow vault token account. Validated in the handler.
    #[account(mut)]
    pub escrow_token: UncheckedAccount<'info>,
    /// CHECK: SPL only — receiver's token account for `mint`. Validated in the handler.
    #[account(mut)]
    pub receiver_token: UncheckedAccount<'info>,
    pub system_program: Program<'info, System>,
    /// CHECK: SPL only. Validated in the handler when `escrow.mint.is_some()`.
    pub token_program: UncheckedAccount<'info>,
}

#[derive(Accounts)]
pub struct Refund<'info> {
    /// Anyone may call once the timelock expires.
    pub caller: Signer<'info>,
    #[account(
        mut,
        seeds = [HTLC_SEED, escrow.fill_id.as_ref(), escrow.hashlock.as_ref()],
        bump = escrow.bump,
        close = refund_addr,
    )]
    pub escrow: Account<'info, HtlcEscrow>,
    /// CHECK: must equal `escrow.refund_addr` (checked in handler); receives the
    /// funds and the reclaimed rent.
    #[account(mut)]
    pub refund_addr: UncheckedAccount<'info>,
    /// CHECK: SPL only — escrow vault token account. Validated in the handler.
    #[account(mut)]
    pub escrow_token: UncheckedAccount<'info>,
    /// CHECK: SPL only — refund address's token account for `mint`. Validated in handler.
    #[account(mut)]
    pub refund_token: UncheckedAccount<'info>,
    pub system_program: Program<'info, System>,
    /// CHECK: SPL only. Validated in the handler when `escrow.mint.is_some()`.
    pub token_program: UncheckedAccount<'info>,
}

#[derive(Accounts)]
pub struct Arbitrate<'info> {
    /// Anyone may submit; authorization comes from the arbiter's ed25519
    /// precompile instruction, verified in the handler via the instructions
    /// sysvar.
    pub caller: Signer<'info>,
    #[account(
        mut,
        seeds = [HTLC_SEED, escrow.fill_id.as_ref(), escrow.hashlock.as_ref()],
        bump = escrow.bump,
        close = refund_addr,
    )]
    pub escrow: Account<'info, HtlcEscrow>,
    /// CHECK: reclaimed rent destination (documented default). Must equal
    /// `escrow.refund_addr` — checked in the handler.
    #[account(mut)]
    pub refund_addr: UncheckedAccount<'info>,
    /// CHECK: SPL only — escrow vault token account. Validated in the handler.
    #[account(mut)]
    pub escrow_token: AccountInfo<'info>,
    pub system_program: Program<'info, System>,
    /// CHECK: SPL only. Validated in the handler when `escrow.mint.is_some()`.
    pub token_program: UncheckedAccount<'info>,
    /// CHECK: the instructions sysvar (address-constrained). Used to locate the
    /// Ed25519Program signature-verification instruction that must immediately
    /// precede this instruction; the precompile's data is parsed but never
    /// trusted for the cryptographic check (the runtime verifies the signature).
    #[account(address = IX_SYSVAR_ID)]
    pub instructions_sysvar: UncheckedAccount<'info>,
    // remaining_accounts: one destination account per recipient, in order —
    //   SOL: writable system accounts owned by each recipient pubkey.
    //   SPL: writable token accounts (mint == escrow.mint) owned by each recipient.
}


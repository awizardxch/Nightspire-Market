/// Authorize an arbiter action via the native Ed25519Program precompile.
///
/// Requires the instruction immediately preceding the current one to be an
/// Ed25519Program signature-verification instruction carrying exactly one
/// signature, signed by `expected_pubkey`, over exactly `expected_msg`, with
/// all signature/pubkey/message bytes inline in that instruction's data
/// (each `*_instruction_index == u16::MAX`).
///
/// Security argument: the Solana runtime cryptographically verifies the ed25519
/// signature when it executes the precompile instruction — a transaction
/// containing a forged precompile instruction never reaches this program.
/// What the program must still bind (and does here) is *which* pubkey and
/// *which* message were verified: an attacker can always append a *validly
/// signed* precompile instruction of their own (e.g. self-signed over a
/// different message), so this check rejects anything not signed by the
/// escrow's arbiter over the exact expected message. The program performs no
/// curve math itself, avoiding the SBF stack-limit violations of in-program
/// ed25519 verification.
fn verify_ed25519_precompile(
    ix_sysvar: &AccountInfo,
    expected_pubkey: &Pubkey,
    expected_msg: &[u8],
) -> Result<()> {
    let current_idx =
        load_current_index_checked(ix_sysvar).map_err(|_| XcmError::InvalidArbiterSignature)?
            as usize;
    // The precompile instruction must immediately precede this one.
    let pre_idx = current_idx
        .checked_sub(1)
        .ok_or(XcmError::InvalidArbiterSignature)?;
    let pre_ix = load_instruction_at_checked(pre_idx, ix_sysvar)
        .map_err(|_| XcmError::InvalidArbiterSignature)?;
    require_keys_eq!(
        pre_ix.program_id,
        ed25519_program::ID,
        XcmError::InvalidArbiterSignature
    );

    // Ed25519Program instruction layout: u8 num_signatures, u8 padding, then
    // per signature: u16 signature_offset, u16 signature_instruction_index,
    // u16 public_key_offset, u16 public_key_instruction_index,
    // u16 message_data_offset, u16 message_data_size,
    // u16 message_instruction_index.
    let data = &pre_ix.data;
    require!(data.len() >= 2 + 14, XcmError::InvalidArbiterSignature);
    require!(data[0] == 1, XcmError::InvalidArbiterSignature);
    let u16_at = |off: usize| -> Result<usize> {
        data.get(off..off + 2)
            .and_then(|b| b.try_into().ok())
            .map(|b: [u8; 2]| u16::from_le_bytes(b) as usize)
            .ok_or(error!(XcmError::InvalidArbiterSignature))
    };
    let sig_off = u16_at(2)?;
    let pk_off = u16_at(6)?;
    let msg_off = u16_at(10)?;
    let msg_size = u16_at(12)?;
    // All signature/pubkey/message bytes must be inline in the precompile
    // instruction itself (u16::MAX = "current instruction"), never borrowed
    // from another instruction's data.
    for off in [4usize, 8, 14] {
        require!(u16_at(off)? == u16::MAX as usize, XcmError::InvalidArbiterSignature);
    }
    let sig_end = sig_off.checked_add(64).ok_or(XcmError::InvalidArbiterSignature)?;
    let pk_end = pk_off.checked_add(32).ok_or(XcmError::InvalidArbiterSignature)?;
    let msg_end = msg_off.checked_add(msg_size).ok_or(XcmError::InvalidArbiterSignature)?;
    require!(data.len() >= sig_end, XcmError::InvalidArbiterSignature);
    require!(data.len() >= pk_end, XcmError::InvalidArbiterSignature);
    require!(data.len() >= msg_end, XcmError::InvalidArbiterSignature);

    require!(
        data[pk_off..pk_end] == expected_pubkey.to_bytes(),
        XcmError::InvalidArbiterSignature
    );
    require!(
        &data[msg_off..msg_end] == expected_msg,
        XcmError::InvalidArbiterSignature
    );
    // The 64 signature bytes were already verified by the runtime when it
    // executed the precompile instruction; pubkey + message binding above is
    // sufficient.
    Ok(())
}

/// The accounts involved in SPL vault operations, collected so one helper pair
/// serves `withdraw`, `refund`, and `arbitrate`.
struct VaultAccounts<'info> {
    escrow: AccountInfo<'info>,
    escrow_token: AccountInfo<'info>,
    dest_token: AccountInfo<'info>,
    rent_dest: AccountInfo<'info>,
    token_program: AccountInfo<'info>,
}

/// Transfer `amount` of SPL tokens from the escrow vault to `dest_token`,
/// validating the vault (mint, PDA authority, balance) and the destination
/// (mint, expected owner). Signed by the escrow PDA.
fn vault_transfer(
    v: &VaultAccounts,
    escrow_key: &Pubkey,
    mint_pk: Pubkey,
    expected_dest_owner: &Pubkey,
    amount: u64,
    seeds: &[&[u8]],
) -> Result<()> {
    require!(
        v.token_program.key() == anchor_spl::token::ID,
        XcmError::InvalidTokenProgram
    );
    let vault =
        TokenAccount::try_deserialize(&mut &v.escrow_token.data.borrow()[..])
            .map_err(|_| XcmError::InvalidTokenAccount)?;
    require!(
        v.escrow_token.owner == &anchor_spl::token::ID,
        XcmError::InvalidTokenAccount
    );
    require!(vault.mint == mint_pk, XcmError::MintMismatch);
    require!(
        vault.owner == *escrow_key,
        XcmError::InvalidTokenAccountOwner
    );
    require!(vault.amount >= amount, XcmError::InsufficientFunds);

    let dest =
        TokenAccount::try_deserialize(&mut &v.dest_token.data.borrow()[..])
            .map_err(|_| XcmError::InvalidTokenAccount)?;
    require!(
        v.dest_token.owner == &anchor_spl::token::ID,
        XcmError::InvalidTokenAccount
    );
    require!(dest.mint == mint_pk, XcmError::MintMismatch);
    require!(
        dest.owner == *expected_dest_owner,
        XcmError::RecipientAccountMismatch
    );
    require!(v.dest_token.is_writable, XcmError::RecipientAccountMismatch);

    let signer_seeds = &[seeds];
    let cpi_ctx = CpiContext::new_with_signer(
        v.token_program.clone(),
        token::Transfer {
            from: v.escrow_token.clone(),
            to: v.dest_token.clone(),
            authority: v.escrow.clone(),
        },
        signer_seeds,
    );
    token::transfer(cpi_ctx, amount)
}

/// Close the SPL vault token account via the SPL `CloseAccount` instruction
/// (authority = escrow PDA), sending reclaimed rent to `rent_dest`.
fn vault_close(v: &VaultAccounts, seeds: &[&[u8]]) -> Result<()> {
    let signer_seeds = &[seeds];
    let cpi_ctx = CpiContext::new_with_signer(
        v.token_program.clone(),
        token::CloseAccount {
            account: v.escrow_token.clone(),
            destination: v.rent_dest.clone(),
            authority: v.escrow.clone(),
        },
        signer_seeds,
    );
    token::close_account(cpi_ctx)
}


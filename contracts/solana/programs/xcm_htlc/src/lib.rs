#[error_code]
pub enum XcmError {
    #[msg("Escrow amount must be greater than zero")]
    InvalidAmount,
    #[msg("Timelock must be in the future at initialization")]
    TimelockInPast,
    #[msg("Receiver/refund address must not be the default pubkey")]
    InvalidAddress,
    #[msg("Preimage does not match the hashlock")]
    InvalidPreimage,
    #[msg("Timelock has expired; the claim window is closed")]
    TimelockExpired,
    #[msg("Timelock has not expired yet")]
    TimelockNotExpired,
    #[msg("Only the exclusive claimer may withdraw during the exclusive window")]
    NotExclusiveClaimer,
    #[msg("Receiver account does not match the escrow's receiver")]
    ReceiverMismatch,
    #[msg("Refund account does not match the escrow's refund_addr")]
    RefundAddrMismatch,
    #[msg("No arbiter was set at lock time; the arbitrate branch is disabled")]
    ArbiterNotSet,
    #[msg("Arbiter signature verification failed")]
    InvalidArbiterSignature,
    #[msg("Recipients and amounts must be non-empty and the same length")]
    PayoutLengthMismatch,
    #[msg("Payout amounts must sum to exactly the escrowed amount")]
    PayoutTotalMismatch,
    #[msg("Not enough recipient accounts were provided")]
    MissingRecipientAccounts,
    #[msg("Recipient account does not match the declared recipient")]
    RecipientAccountMismatch,
    #[msg("Expected the SPL Token program")]
    InvalidTokenProgram,
    #[msg("Not a valid SPL token account")]
    InvalidTokenAccount,
    #[msg("Token account mint does not match the escrow mint")]
    MintMismatch,
    #[msg("Token account owner is not the expected authority")]
    InvalidTokenAccountOwner,
    #[msg("Insufficient funds in the token account")]
    InsufficientFunds,
    #[msg("Escrow vault token account must be empty at initialization")]
    VaultNotEmpty,
}

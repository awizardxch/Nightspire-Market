/// On-chain HTLC escrow. Role-explicit per SPEC.md §5: the program knows
/// `receiver` / `refund_addr` / keys — never "maker"/"taker" labels.
#[account]
pub struct HtlcEscrow {
    /// Claim branch pays here.
    pub receiver: Pubkey,
    /// Timelock branch pays here. EXPLICIT — refund never assumes a sender.
    pub refund_addr: Pubkey,
    /// sha256(secret); secret generated by the maker per fill.
    pub hashlock: [u8; 32],
    /// Unix timestamp; claim requires now < timelock, refund requires now >= timelock.
    pub timelock: i64,
    /// None = native SOL escrow; Some = SPL mint.
    pub mint: Option<Pubkey>,
    /// Escrowed amount (lamports / token base units).
    pub amount: u64,
    /// sha256(offerId || fillNonce); unique per fill, bound into the PDA seeds.
    pub fill_id: [u8; 32],
    /// Opt-in MEDIATED arbitration key. None = pure HTLC.
    pub arbiter: Option<Pubkey>,
    /// Auction-winner exclusive claim window (§8).
    pub exclusive_claimer: Option<Pubkey>,
    pub exclusive_until: i64,
    /// PDA bump for ["htlc", fill_id, hashlock].
    pub bump: u8,
}

impl HtlcEscrow {
    /// 8 (discriminator) + 32 + 32 + 32 + 8 + (1+32) + 8 + 32 + (1+32) + (1+32) + 8 + 1
    pub const SPACE: usize = 260;
}

